"""心弦好感度 - 一位小数精度工具。

好感度支持到小数点后一位。本模块是舍入与显示的唯一真相源：
所有数值在写边界（落库 / 设定）经 round1 收敛到 1 位小数，
显示时经 fmt 去掉多余的 .0（50 → "50"，50.5 → "50.5"）。

浮点漂移控制：每日限幅等累积场景会出现 1e-16 量级误差，
在每个写边界 round1 即可吸收，无需上定点数（整数×10）。
"""

from __future__ import annotations


def round1(x) -> float:
    """收敛到小数点后一位。

    使用内置 round（银行家舍入，半数偶）。对好感度这类以
    0.1 为步进的值，几乎不会命中 0.05 精确边界，影响可忽略；
    真正承重的是"在每个写边界都 round1"这一纪律。
    """
    return round(float(x), 1)


def fmt(x) -> str:
    """显示用字符串：整数值不带小数点，否则保留 1 位小数。"""
    v = round1(x)
    return str(int(v)) if v == int(v) else str(v)
